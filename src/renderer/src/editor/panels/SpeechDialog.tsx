// Text to speech: turns typed text into a voice-over clip, optionally with matching subtitles.

import type { ReactNode } from 'react';
import { useEffect, useState } from 'react';
import { Speech } from 'lucide-react';
import { SCRIPT_MAX_CHARS } from '@shared/constants';
import { chunkCue, splitSentences } from '@shared/subtitles';
import { snapToFrame } from '@shared/time';
import type { ID, VoiceInfo } from '@shared/types';
import { Modal } from '@/components/Modal';
import { Button, Field, Notice, Slider, Spinner, Switch } from '@/components/ui';
import { api, errorMessage } from '@/lib/api';
import type { ProjectPlace } from '@/lib/projects';
import { addSubtitles, useEditor, whenOpen } from '@/store/editor';
import { navigate, showModal, toast } from '@/store/ui';
import { offerToMuteUnder } from '../actions';
import { addToTimeline } from '../importing';

export function VoicePicker({ voices, value, onChange }: { voices: VoiceInfo[]; value: string; onChange: (v: string) => void }): ReactNode {
  return (
    <select className="select" aria-label="Voice" value={value} onChange={(e) => onChange(e.target.value)}>
      {voices.map((v) => (
        <option key={v.id} value={v.id}>
          {v.name}
          {v.lang ? ` (${v.lang})` : ''}
        </option>
      ))}
    </select>
  );
}

function SpeechBody({ projectId, place, close }: { projectId: ID | null; place: ProjectPlace; close: () => void }): ReactNode {
  const [voices, setVoices] = useState<VoiceInfo[] | null>(null);
  const [voice, setVoice] = useState('');
  const [rate, setRate] = useState(1);
  const [text, setText] = useState('');
  const [subtitles, setSubtitles] = useState(true);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');

  useEffect(() => {
    void api.voice.list().then((list) => {
      setVoices(list);
      if (list[0]) setVoice(list[0].id);
    });
  }, []);

  const generate = async (): Promise<void> => {
    setBusy(true);
    setError('');
    try {
      const sentences = splitSentences(text);
      const name = sentences[0]?.slice(0, 40) || 'Voice-over';
      // Started from the dashboard: the project begins now that there is something to put in it.
      const target = projectId ?? (await api.library.createProject({ ...place, name })).id;
      if (!projectId) {
        await navigate({ page: 'editor', projectId: target });
        await whenOpen(target);
      }
      const { asset, timings } = await api.voice.speak({ sentences, voice, rate, name, target: { scope: 'project', projectId: target } });
      const at = snapToFrame(useEditor.getState().playhead, useEditor.getState().doc?.settings.fps ?? 30);
      await addToTimeline([asset]);
      const voiceId = useEditor.getState().selection[0];
      if (subtitles) addSubtitles(sentences.flatMap((s, i) => chunkCue(s, at + timings[i].start, at + timings[i].end)));
      toast('Voice-over added to the timeline.', { kind: 'success' });
      close();
      await offerToMuteUnder(voiceId);
    } catch (err) {
      setError(errorMessage(err));
      setBusy(false);
    }
  };

  return (
    <Modal
      title="Text to speech"
      size="wide"
      onClose={close}
      dismissable={!busy}
      footer={
        <>
          <Button onClick={close} disabled={busy}>
            Cancel
          </Button>
          <Button variant="primary" icon={busy ? <Spinner /> : <Speech size={15} />} disabled={busy || !text.trim() || !voice} onClick={() => void generate()}>
            {busy ? 'Generating…' : 'Add voice-over'}
          </Button>
        </>
      }
    >
      {voices === null ? (
        <div className="row">
          <Spinner /> <span className="muted">Finding voices…</span>
        </div>
      ) : voices.length === 0 ? (
        <Notice kind="warning" icon={<Speech size={15} />}>
          No text-to-speech voices are installed on this computer.
        </Notice>
      ) : (
        <>
          <Field label="Text" hint={`${text.length.toLocaleString()} / ${SCRIPT_MAX_CHARS.toLocaleString()} characters`}>
            <textarea className="textarea" rows={7} maxLength={SCRIPT_MAX_CHARS} placeholder="Type what the voice should say" value={text} onChange={(e) => setText(e.target.value)} />
          </Field>
          <div className="form-grid">
            <Field label="Voice">
              <VoicePicker voices={voices} value={voice} onChange={setVoice} />
            </Field>
            <Field label={`Speed · ${rate.toFixed(1)}x`}>
              <Slider label="Speaking speed" min={0.6} max={1.6} step={0.1} value={rate} onChange={setRate} />
            </Field>
          </div>
          <div className="field-row">
            <span className="label">Add matching subtitles</span>
            <Switch label="Add matching subtitles" checked={subtitles} onChange={setSubtitles} />
          </div>
          <p className="faint">Speech is generated by your operating system's voices, on this computer.</p>
        </>
      )}
      {error && (
        <Notice kind="error" icon={<Speech size={15} />}>
          {error}
        </Notice>
      )}
    </Modal>
  );
}

export function openSpeechDialog(projectId: ID | null, place: ProjectPlace = {}): void {
  void showModal<void>((close) => <SpeechBody projectId={projectId} place={place} close={() => close()} />);
}
